#include <iostream>
#include <cmath>
using namespace std;

int main()
{
    int num1 = 4, num2 = 2;

    cout << "Power: " << pow(num1, num2) << endl;  // Power
    cout << "Square root: " << sqrt(num1) << endl; // Square root

    num1 = -4;
    cout << "Absolute value: " << abs(num1) << endl; // Absolute value

    return 0;
}